"""TRAITS.md: the by-skill and by-trait views."""

from __future__ import annotations

from curation.registry.config import RegistryConfig
from curation.registry.ledger import _adopt_target, effective_traits_for
from curation.registry.loaders import load_records
from curation.registry.models import (
    Event,
    OursTraitEntry,
    Placement,
    SharingEntry,
    TraitDefinition,
    UpstreamTraitEntry,
)
from curation.registry.traits import _doc_traits, _ours_traits, _upstream_traits
from curation.registry.views.index import _domain_key
from curation.registry.vocab import DOMAIN_ORDER, STAGE_ORDER


def _ruling_suffix(ruling: Event | None, forward: dict[str, str]) -> str:
    """The ` — <kind>` suffix (plus ` → <target>` for an adopt, and `, pending
    <bead>`) for a trait's effective ruling; empty when unruled (§7). Reuses the
    ledger's effective rulings so TRAITS.md never disagrees with the ledger."""
    if ruling is None:
        return ""
    if ruling.kind == "adopt" and ruling.skill:
        pending = f", pending {ruling.pending}" if ruling.pending else ""
        return f" — adopt{pending} → {_adopt_target(ruling, forward)}"
    return f" — {ruling.kind}"


def _placement_key(p: Placement) -> tuple[tuple[int, str], int, str]:
    return (
        _domain_key(p.domain),
        STAGE_ORDER.index(p.stage) if p.stage in STAGE_ORDER else len(STAGE_ORDER),
        p.substage,
    )


def render_traits(
    cfg: RegistryConfig,
    current: dict[str, Event],
    forward: dict[str, str],
    definitions: dict[str, TraitDefinition],
    traits: dict[str, OursTraitEntry | UpstreamTraitEntry],
    shared: dict[str, list[str]],
    sharing: dict[str, SharingEntry],
) -> str:
    """TRAITS.md: a by-skill and a by-trait view of every trait (§7), then the
    shared traits (stages-design §Shared traits)."""
    ours = _ours_traits(traits)
    docs = _doc_traits(traits)
    upstream = _upstream_traits(traits)
    records = {fm.skill: fm for fm in load_records(cfg).values()}

    def defn(tid: str) -> str:
        d = definitions.get(tid)
        return d.definition if d else ""

    lines = [
        "# Traits",
        "",
        "<!-- GENERATED by registry.py build. Do not edit. -->",
        "",
        (
            "By skill, then by trait. The vocabulary and lists live in "
            "`trait-definitions.yaml` and `traits/`; rulings come from the ledger."
        ),
        "",
        "## By skill",
        "",
        "### Ours",
        "",
    ]
    # Ours, grouped by the record's placement.
    placed_ours = [
        (records[skill], entry) for skill, entry in ours.items() if skill in records
    ]
    for fm, entry in sorted(
        placed_ours,
        key=lambda t: (_domain_key(t[0].domain), t[0].stage, t[0].substage, t[0].skill),
    ):
        lines.append(f"#### {fm.domain} · {fm.stage} · {fm.substage} — {fm.skill}")
        for tid in entry.traits:
            lines.append(f"- `{tid}`: {defn(tid)}")
        lines.append("")
    # Our documents (`doc:` entries), in a section of their own.
    if docs:
        lines.append("### Docs")
        lines.append("")
        for key, entry in sorted(docs.items()):
            lines.append(f"#### {key}")
            for tid in entry.traits:
                lines.append(f"- `{tid}`: {defn(tid)}")
            lines.append("")
    # Upstream, grouped by repo then placement, with the effective ruling suffix.
    by_repo: dict[str, list[tuple[str, UpstreamTraitEntry]]] = {}
    for subject, up in upstream.items():
        by_repo.setdefault(subject.partition(":")[0], []).append((subject, up))
    for repo in sorted(by_repo):
        lines.append(f"### {repo}")
        lines.append("")
        for subject, up in sorted(
            by_repo[repo], key=lambda t: (_placement_key(t[1].newest.placement), t[0])
        ):
            p = up.newest.placement
            name = subject.partition(":")[2]
            lines.append(f"#### {p.domain} · {p.stage} · {p.substage} — {name}")
            trait_events = effective_traits_for(current, subject)
            for tid in up.newest.traits:
                suffix = _ruling_suffix(trait_events.get(tid), forward)
                lines.append(f"- `{tid}`: {defn(tid)}{suffix}")
            lines.append("")

    # By trait: every defined trait (plus any listed trait without a definition),
    # grouped by the definition's placement.
    lines.append("## By trait")
    lines.append("")
    listed = {tid for entry in ours.values() for tid in entry.traits}
    listed |= {tid for entry in docs.values() for tid in entry.traits}
    listed |= {tid for entry in upstream.values() for tid in entry.newest.traits}
    all_ids = set(definitions) | listed
    ordered = sorted(
        all_ids,
        key=lambda tid: (
            _placement_key(definitions[tid].placement)
            if tid in definitions
            else (len(DOMAIN_ORDER), len(STAGE_ORDER), ""),
            tid,
        ),
    )
    heading = None
    for tid in ordered:
        d = definitions.get(tid)
        place = d.placement if d else None
        here = (
            f"{place.domain} · {place.stage} · {place.substage}"
            if place
            else "(undefined)"
        )
        if here != heading:
            heading = here
            lines.append(f"### {here}")
            lines.append("")
        retired = " *(retired)*" if d and d.retired else ""
        lines.append(f"#### `{tid}`{retired}")
        if d:
            lines.append(f"{d.definition}")
        holders = sorted(skill for skill, e in ours.items() if tid in e.traits)
        for skill in holders:
            lines.append(f"- ours: `{skill}`")
        for key in sorted(k for k, e in docs.items() if tid in e.traits):
            lines.append(f"- `{key}`")
        for subject, up in sorted(upstream.items()):
            if tid not in up.newest.traits:
                continue
            ruling = effective_traits_for(current, subject).get(tid)
            lines.append(f"- `{subject}`{_ruling_suffix(ruling, forward)}")
        lines.append("")

    lines += [
        "## Shared traits",
        "",
        (
            "Traits listed by two or more of our active skills (`doc:AGENTS.md` "
            "counts); the reason lives in `trait-sharing.yaml`."
        ),
        "",
    ]
    if shared:
        lines += ["| Trait | Holders | Why |", "|---|---|---|"]
        for tid, names in shared.items():
            justified = sharing.get(tid)
            why = " ".join(justified.why.split()) if justified else "not yet justified"
            lines.append(f"| `{tid}` | {', '.join(names)} | {why} |")
    else:
        lines.append("None.")
    return "\n".join(lines).rstrip() + "\n"
