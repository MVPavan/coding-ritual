"""STEPS.md: every playbook's steps, and where a trait or call recurs (St2, St4)."""

from __future__ import annotations

from curation.registry.steps import Call, Load, Playbook


def _cell(text: str) -> str:
    return " ".join(text.split()).replace("|", "\\|")


def _call(call: Call) -> str:
    out = f"`{call.to}`"
    if call.needs:
        out += " needs " + ", ".join(f"`{t}`" for t in call.needs)
    if call.when:
        out += f" (when: {_cell(call.when)})"
    return out


def _load(book: Playbook, load: Load) -> str:
    out = f"`{book.load_path(load) or load.path}`"
    if load.when:
        out += f" (when: {_cell(load.when)})"
    return out


def _recurrence(title: str, where: dict[str, dict[str, list[str]]]) -> list[str]:
    """One table of the items used by two or more playbooks, each with the
    steps (or `playbook` for a playbook-level trait) that use it."""
    lines = [f"### {title}", ""]
    shared = {k: v for k, v in sorted(where.items()) if len(v) > 1}
    if not shared:
        return [*lines, "None.", ""]
    lines += ["| Item | Playbooks |", "|---|---|"]
    for item, books in shared.items():
        used = "; ".join(
            f"{name}: {', '.join(f'`{s}`' for s in places)}"
            for name, places in sorted(books.items())
        )
        lines.append(f"| `{item}` | {used} |")
    return [*lines, ""]


def render_steps(playbooks: dict[str, Playbook]) -> str:
    lines = [
        "# Steps",
        "",
        "<!-- GENERATED by registry.py build. Do not edit. -->",
        "",
        (
            "Every playbook's steps, read from the step lists in each playbook's "
            "frontmatter (`.repo-context/unit-kinds.md` St2). Traits are a step's "
            "own actions (T3); calls name the units it invokes; loads name the "
            "references it reads, by repository path (St1)."
        ),
        "",
    ]
    traits_where: dict[str, dict[str, list[str]]] = {}
    calls_where: dict[str, dict[str, list[str]]] = {}
    for name, book in sorted(playbooks.items()):
        lines += [f"## {name}", "", f"`{book.path}`", ""]
        lines.append(f"Trigger: {_cell(book.trigger)}")
        lines.append("")
        if book.traits:
            lines.append("Playbook traits: " + ", ".join(f"`{t}`" for t in book.traits))
            lines.append("")
        for tid in book.traits:
            traits_where.setdefault(tid, {}).setdefault(name, []).append("playbook")
        lines += [
            "| Step | When | Traits | Calls | Loads |",
            "|---|---|---|---|---|",
        ]
        for step in book.steps:
            traits = ", ".join(f"`{t}`" for t in step.traits)
            calls = "; ".join(_call(c) for c in step.calls)
            loads = "; ".join(_load(book, x) for x in step.loads)
            lines.append(
                f"| `{step.id}` | {_cell(step.when)} | {traits} | {calls} | {loads} |"
            )
            for tid in step.traits:
                traits_where.setdefault(tid, {}).setdefault(name, []).append(step.id)
            for c in step.calls:
                calls_where.setdefault(c.to, {}).setdefault(name, []).append(step.id)
        lines.append("")
    if not playbooks:
        lines += ["No playbooks.", ""]
    lines += [
        "## Recurrence",
        "",
        (
            "Traits and calls used by two or more playbooks. Repeating a step "
            "is fine; the same own action in two playbooks is the signal to "
            "make it a skill (St4)."
        ),
        "",
    ]
    lines += _recurrence("Traits", traits_where)
    lines += _recurrence("Calls", calls_where)
    return "\n".join(lines).rstrip() + "\n"
